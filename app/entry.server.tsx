import { PassThrough } from "node:stream";
import type { AppLoadContext, EntryContext } from "@remix-run/node";
import { createReadableStreamFromReadable } from "@remix-run/node";
import { RemixServer } from "@remix-run/react";
import { isbot } from "isbot";
import { renderToPipeableStream } from "react-dom/server";

const ABORT_DELAY = 5_000;

/**
 * ✅ Ajoute les headers de sécurité HTTP pour protéger contre diverses attaques
 */
function setSecurityHeaders(headers: Headers) {
  // Protection contre le clickjacking
  headers.set("X-Frame-Options", "DENY");

  // Prévient le MIME-type sniffing
  headers.set("X-Content-Type-Options", "nosniff");

  // Politique de référent pour protéger la vie privée
  headers.set("Referrer-Policy", "strict-origin-when-cross-origin");

  // Permissions pour les fonctionnalités du navigateur
  headers.set("Permissions-Policy", "geolocation=(), microphone=(), camera=()");

  // Content Security Policy (CSP) - À ajuster selon vos besoins
  // Note: 'unsafe-inline' nécessaire pour GSAP et animations inline
  headers.set(
    "Content-Security-Policy",
    "default-src 'self'; " +
    "script-src 'self' 'unsafe-inline' 'unsafe-eval' https://www.googletagmanager.com https://www.google-analytics.com; " +
    "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; " +
    "font-src 'self' https://fonts.gstatic.com; " +
    "img-src 'self' data: https:; " +
    "connect-src 'self' https://www.google-analytics.com; " +
    "frame-ancestors 'none';"
  );

  // Force HTTPS en production (décommenter si vous avez HTTPS configuré)
  // headers.set("Strict-Transport-Security", "max-age=31536000; includeSubDomains");
}

export default function handleRequest(
  request: Request,
  responseStatusCode: number,
  responseHeaders: Headers,
  remixContext: EntryContext,
  loadContext: AppLoadContext
) {
  return isbot(request.headers.get("user-agent") || "")
    ? handleBotRequest(
        request,
        responseStatusCode,
        responseHeaders,
        remixContext
      )
    : handleBrowserRequest(
        request,
        responseStatusCode,
        responseHeaders,
        remixContext
      );
}

function handleBotRequest(
  request: Request,
  responseStatusCode: number,
  responseHeaders: Headers,
  remixContext: EntryContext
) {
  return new Promise((resolve, reject) => {
    let shellRendered = false;
    const { pipe, abort } = renderToPipeableStream(
      <RemixServer
        context={remixContext}
        url={request.url}
        abortDelay={ABORT_DELAY}
      />,
      {
        onAllReady() {
          shellRendered = true;
          const body = new PassThrough();
          const stream = createReadableStreamFromReadable(body);
          responseHeaders.set("Content-Type", "text/html");
          // ✅ Ajouter les headers de sécurité
          setSecurityHeaders(responseHeaders);
          resolve(
            new Response(stream, {
              headers: responseHeaders,
              status: responseStatusCode,
            })
          );
          pipe(body);
        },
        onShellError(error: unknown) {
          reject(error);
        },
        onError(error: unknown) {
          responseStatusCode = 500;
          if (shellRendered) {
            console.error(error);
          }
        },
      }
    );
    setTimeout(abort, ABORT_DELAY);
  });
}

